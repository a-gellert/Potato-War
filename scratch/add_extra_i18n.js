const targets = {
  en: '\t\tbarracks_btn = "BARRACKS",',
  ru: '\t\tbarracks_btn = "КАЗАРМА",',
  tr: '\t\tbarracks_btn = "KIŞLA",',
  es: '\t\tbarracks_btn = "CUARTEL",',
  pt: '\t\tbarracks_btn = "QUARTEL",',
  fr: '\t\tbarracks_btn = "CASERNE",'
};

for (const lang of ['en', 'ru', 'tr', 'es', 'pt', 'fr']) {
  const target = targets[lang];
  if (!content.includes(target)) {
    console.error('Target not found for lang:', lang);
    process.exit(1);
  }
  const replacement = target + '\n' + extraTranslations[lang];
  content = content.replace(target, replacement);
}

fs.writeFileSync('lua_modules/i18n.lua', content, 'utf8');
console.log('Successfully injected extra translations for all 6 languages');
